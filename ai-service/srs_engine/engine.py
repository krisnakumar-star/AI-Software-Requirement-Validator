"""Public entry points of the analysis engine."""
from __future__ import annotations

from .analyzer import analyze_requirement
from .document import analyze_document
from .parse import INLINE_ID_RE
from .similarity import SEMANTIC

ENGINE_VERSION = "10.0.0"
PROVIDER = "built-in NLP analysis engine"


def engine_status() -> dict:
    return {"engine_version": ENGINE_VERSION, "provider": PROVIDER, "external_ai_services": False, **SEMANTIC.status()}


def _legacy_expert_review(a: dict) -> dict:
    """Older response shape kept for backward compatibility with saved data and clients."""
    verdict = {"Poor": "Needs substantial revision", "Needs Improvement": "Needs clarification"}.get(a["status"], "No major issue detected")
    return {
        "review_verdict": verdict,
        "risk_level": {"Critical": "High", "High": "High", "Medium": "Moderate"}.get(a["priority"], "Low"),
        "executive_summary": a["explanation"],
        "requirement_type_interpretation": {"primary_type": a["classification"], "detected_categories": a["categories"]},
        "strengths": [s["strength"] + f" ({s['evidence']})" for s in a["strengths"]],
        "dimension_assessment": [{"dimension": d, "score": v, "interpretation": "Strong" if v >= 85 else "Needs attention" if v >= 65 else "Weak"}
                                 for d, v in a["dimension_scores"].items()],
        "detailed_reasoning": [{"finding": f["message"], "why_it_matters": f["why_it_matters"], "recommended_action": f["recommendation"],
                                "severity": f["severity"]} for f in a["detailed_findings"]],
        "questions_for_requirement_owner": a["clarification_questions"],
        "suggested_acceptance_criteria": a["acceptance_criteria"],
        "illustrative_test_scenarios": a["test_scenarios"],
        "prioritized_improvement_plan": [{"priority": f["severity"], "action": f["recommendation"], "reason": f["message"]} for f in a["detailed_findings"]],
        "review_limitations": [
            "Generated by a deterministic NLP and rule engine, not by a trained neural network or external AI service.",
            "A finding is a review signal, not proof of a defect; absence of findings is not proof of correctness.",
            "Thresholds, business rules and legal obligations must be confirmed with stakeholders ([TBD] marks unknowns).",
        ],
    }


def analyze_single(text: str, requirement_id: str | None = None, source: str | None = None, section: str | None = None) -> dict:
    a = analyze_requirement(text, requirement_id, id_generated=requirement_id is None, source=source, section=section)
    a["expert_review"] = _legacy_expert_review(a)
    return a


def analyze_batch(records: list[dict], project_name: str | None = None) -> dict:
    """records: [{text, requirement_id?, section?, source?}] in document order."""
    items, used = [], set()
    for index, record in enumerate(records):
        text = record["text"]
        rid = (record.get("requirement_id") or "").strip() or None
        generated = False
        if not rid:
            match = INLINE_ID_RE.match(text.strip())
            rid = match.group(1) if match else None
        if not rid:
            rid, generated = f"REQ-{index + 1:03d}", True
        analysis = analyze_requirement(text, rid, id_generated=generated,
                                       source=record.get("source") or project_name, section=record.get("section"))
        items.append({"id": rid, "text": text, "analysis": analysis})
        used.add(rid)
    report = analyze_document(items)
    for it in items:
        it["analysis"]["expert_review"] = _legacy_expert_review(it["analysis"])
    return {"analyses": [it["analysis"] for it in items], "document_report": report}
